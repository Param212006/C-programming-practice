#include<stdio.h>
int main(){
	char a='A';
	int b=12;
	float c=3.12;
	double d=34.21;
	long e=234;
	long double f=345;
	printf("\n char a= %c",a);
	printf("\n int b= %d",b);
	printf("\n float c= %f",c);
	printf("\n double d= %lf",d);
	printf("\n long e=%ld",e);
	printf("\n long double f=%LF",f);
	
	return 0;
}